export function apiErrorMessage(status: number, code?: string): string {
  const messages: Record<string, string> = {
    READER_NOT_FOUND: 'Читача не знайдено. Перевірте адресу або поверніться до списку.',
    READER_CATEGORY_NOT_FOUND: 'Категорію не знайдено. Оновіть список категорій і повторіть вибір.',
    READER_CATEGORY_CONFLICT: 'Категорія більше недоступна. Оновіть дані перед повторною спробою.',
    READER_WRITE_CONFLICT: 'Профіль одночасно змінено. Оновіть дані перед повторною спробою.',
    INVENTORY_CODE_EXISTS: 'Цей інвентарний номер уже використовується. Вкажіть інший номер.',
    COPY_HAS_RENTALS: 'Примірник має історію прокатів, тому його не можна видалити.',
    COPY_ACTIVE_RENTAL: 'Примірник має активний прокат. Змінити його статус зараз неможливо.',
    COPY_STATUS_CONFLICT: 'Поточний статус примірника не дозволяє цю дію. Оновіть дані.',
    COPY_WRITE_CONFLICT: 'Книгу або примірник одночасно змінено. Оновіть дані перед повторною спробою.',
    COPY_RELATION_CONFLICT: 'Пов’язані записи не дозволяють виконати цю дію.',
    BOOK_ARCHIVED: 'Книгу вже архівовано. Зміни книги та її примірників недоступні.',
    BOOK_NOT_FOUND: 'Книгу не знайдено. Можливо, її більше немає за цією адресою.',
    COPY_NOT_FOUND: 'Примірник не знайдено. Оновіть список примірників.',
    INVALID_CREDENTIALS: 'Неправильна електронна адреса або пароль.',
    AUTH_REQUIRED: 'Сеанс завершився. Увійдіть знову.',
    AUTH_VALIDATION_ERROR: 'Перевірте поля форми та вимоги до пароля.',
    AUTH_BUSY: 'Сервер обробляє забагато операцій із паролями. Спробуйте ще раз за мить.',
    WRONG_OLD_PASSWORD: 'Поточний пароль неправильний.',
    LOGIN_RATE_LIMITED: 'Забагато спроб входу. Спробуйте пізніше.',
    CSRF_REJECTED: 'Сервер відхилив запит із цієї адреси застосунку.',
    STAFF_EMAIL_EXISTS: 'Працівник із такою електронною адресою вже існує.',
    LAST_ACTIVE_ADMIN: 'Має залишитися щонайменше один активний адміністратор.',
  };
  if (code && messages[code]) return messages[code];
  if (status === 400) return 'Некоректні дані запиту. Перевірте заповнені поля та параметри адреси.';
  if (status === 403) return 'Ваша роль не дозволяє виконати цю дію.';
  if (status === 404) return 'Запис не знайдено. Оновіть дані.';
  if (status === 409) return 'Дія суперечить поточному стану запису. Оновіть дані та перевірте умови операції.';
  if (status >= 500) return 'Сервер тимчасово не може виконати операцію. Спробуйте ще раз пізніше.';
  return `Не вдалося виконати запит (HTTP ${status}).`;
}
